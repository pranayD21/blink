/**
 * Deterministic English preview of a compiled policy (§8.8).
 *
 * Template rendering only — no model. It exposes exactly what was encoded so
 * the policy owner can compare it with the source text. It does not prove the
 * encoding is faithful; the owner's approval of the bundle hash does that.
 */
import { predicatePhrase } from "../predicates/registry";
import type { EnumerationReport } from "./enumerate";
import type { GuardExpr, Inventory, Monitor, RulesDoc } from "./schema";
import { buildGuardTree } from "./schema";

/** "the statement is about the covered issuer AND NOT (the information matches a verified public source)". */
export function guardToEnglish(guard: GuardExpr, nested = false): string {
  switch (guard.op) {
    case "pred":
      return predicatePhrase(guard.name, guard.params);
    case "not":
      return `NOT (${guardToEnglish(guard.arg, false)})`;
    case "and":
    case "or": {
      const joined = guard.args.map((arg) => guardToEnglish(arg, true)).join(guard.op === "and" ? " AND " : " OR ");
      return nested ? `(${joined})` : joined;
    }
  }
}

const ON_TRUE: Record<string, string> = {
  open_review: "open a compliance review",
  open_review_and_escalate: "open a compliance review and request escalation to a senior compliance officer",
};
const ON_INDETERMINATE: Record<string, string> = {
  open_context_task: "open a context task and seek clarification before any conclusion",
  open_review: "open a compliance review",
};

function oneLine(text: string): string {
  return text.replace(/\s+/g, " ").trim();
}

export interface DecompileInput {
  title: string;
  inventory: Inventory | null;
  rulesDoc: RulesDoc;
  monitors: Monitor[];
  enumeration: EnumerationReport[];
}

export function decompilePolicy(input: DecompileInput): string {
  const clauses = new Map((input.inventory?.clauses ?? []).map((c) => [c.clause_id, c]));
  const lines: string[] = [];
  lines.push(`# ${input.title} — compiled preview`);
  lines.push("");
  lines.push(
    "_Generated by code from the compiled rules and monitors. This shows what was encoded; it does not prove the encoding matches the policy's intent. Approving the bundle hash is the policy owner's statement that it does._",
  );

  for (const rule of input.rulesDoc.rules) {
    const monitor = input.monitors.find((m) => m.rule_id === rule.rule_id);
    const report = input.enumeration.find((e) => e.rule_id === rule.rule_id);
    const built = buildGuardTree(rule.guard);

    lines.push("");
    lines.push(`## Rule ${rule.rule_id} — ${oneLine(rule.intent)}`);
    lines.push("");
    lines.push(`**Severity:** ${rule.severity}`);
    lines.push("");
    lines.push("**Source clauses**");
    for (const id of rule.source_clause_ids) {
      const clause = clauses.get(id);
      lines.push(clause ? `- ${id} (${clause.paragraph}, ${clause.kind}): “${oneLine(clause.verbatim)}”` : `- ${id}`);
    }
    if (rule.exception_clause_ids.length > 0) {
      lines.push("");
      lines.push("**Exceptions folded into the condition**");
      for (const id of rule.exception_clause_ids) {
        const clause = clauses.get(id);
        lines.push(clause ? `- ${id} (${clause.paragraph}): “${oneLine(clause.verbatim)}”` : `- ${id}`);
      }
    }
    lines.push("");
    lines.push("**Condition**");
    lines.push("");
    lines.push(built.ok ? `> ${guardToEnglish(built.tree)}` : `> (guard could not be rebuilt: ${built.reason})`);
    lines.push("");
    lines.push(`- When the condition is **true**: ${ON_TRUE[rule.on_true] ?? rule.on_true}.`);
    lines.push(`- When evidence is **missing or conflicting**: ${ON_INDETERMINATE[rule.on_indeterminate] ?? rule.on_indeterminate}.`);
    lines.push("- When the condition is **false**: the monitor records \"not triggered\". This is not a clearance; later context can re-trigger it.");

    if (monitor) {
      lines.push("");
      lines.push(`**Monitor ${monitor.monitor_id} transitions**`);
      lines.push("");
      lines.push("| # | From | Event | Condition is | To | Effects |");
      lines.push("|---|---|---|---|---|---|");
      for (const t of monitor.transitions) {
        lines.push(`| ${t.id} | ${t.from.join(", ")} | ${t.event} | ${t.result_is} | ${t.to} | ${t.effects.join(", ") || "—"} |`);
      }
      lines.push("");
      lines.push("Any other event leaves the state unchanged and is written to the audit log.");
    }
    if (report) {
      lines.push("");
      lines.push(
        `**Exhaustive check:** ${report.combinations.toLocaleString("en-US")} evidence combinations over ${report.predicates.length} predicates → ` +
          `${report.outcomes.true.toLocaleString("en-US")} true, ${report.outcomes.false.toLocaleString("en-US")} false, ${report.outcomes.indeterminate.toLocaleString("en-US")} indeterminate. ` +
          `Deterministic: ${report.determinism.pass ? "yes" : "NO"}. Indeterminate handled: ${report.indeterminate_handled ? "yes" : "NO"}. ` +
          `Coverage: ${report.coverage.handled}/${report.coverage.total} (state, event, result) triples have a transition.`,
      );
    }
  }

  lines.push("");
  lines.push("## Not automated — reviewer must apply manually");
  lines.push("");
  if (input.rulesDoc.unsupported_clauses.length === 0) {
    lines.push("_None._");
  } else {
    for (const u of input.rulesDoc.unsupported_clauses) {
      const clause = clauses.get(u.clause_id);
      lines.push(clause ? `- ${u.clause_id} (${clause.paragraph}): “${oneLine(clause.verbatim)}” — ${oneLine(u.reason)}` : `- ${u.clause_id} — ${oneLine(u.reason)}`);
    }
  }
  lines.push("");
  return lines.join("\n");
}
